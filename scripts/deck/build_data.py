"""Writes scripts/deck/data.js for the showcase deck from content/work.json and content/worlds.ts.
Run from the repo root: python3 scripts/deck/build_data.py"""
import json, re

work = json.load(open('content/work.json'))
worlds = open('content/worlds.ts').read()


def blurb_of(name):
    m = re.search(r"name: (['\"])" + re.escape(name) + r"\1[^\n]*?blurb: (['\"])(.*?)\2 \}", worlds)
    return m.group(3).replace("\\'", "'") if m else ''


def world_blurb(slug):
    m = re.search(r"slug: '" + slug + r"'.*?\n\s*blurb: '(.*?)',", worlds, re.S)
    return m.group(1).replace("\\'", "'") if m else ''


def pieces(items):
    return [[p['src'].replace('/img/work/', ''), p['w'], p['h'], p['name'], p.get('mock', 'plain')] for p in items]


sections = []
brands = ["Esorae Home", "The Stewards' Table", "LonePay", "Esorae Foundation", "eurban", "O5 Dynamix", "OJKonsult"]
years = {"The Stewards' Table": '2026', 'LonePay': '2025'}
for i, b in enumerate(brands):
    sections.append({'kind': f'Branding · {i + 1:02d}', 'name': b, 'blurb': blurb_of(b), 'year': years.get(b, '2025'),
                     'pieces': pieces([p for p in work['branding'] if p.get('group') == b])})
sections.append({'kind': 'Brand & campaign', 'name': 'Fission', 'blurb': world_blurb('fission'), 'year': '2025', 'pieces': pieces(work['fission'])})
sections.append({'kind': 'UI / UX', 'name': 'Product interfaces', 'blurb': world_blurb('uiux'), 'year': '2025', 'pieces': pieces(work['uiux'])})
for g in ['Axislink', 'Profit AI', 'Hashcake', 'Token launches']:
    sections.append({'kind': 'Web3', 'name': g, 'blurb': blurb_of(g), 'year': '2026', 'pieces': pieces([p for p in work['web3'] if p.get('group') == g])})
sections.append({'kind': 'Social & print', 'name': 'Flyers & Banners', 'blurb': world_blurb('flyers'), 'year': '2026', 'pieces': pieces(work['flyers'])})

for x in sections: x['id'] = 'sec-' + re.sub(r'[^a-z0-9]+', '', x['name'].lower())
open('scripts/deck/data.js', 'w').write('// generated by build_data.py\nwindow.SECTIONS = ' + json.dumps(sections, ensure_ascii=False, indent=1) + ';\n')
print(len(sections), 'sections,', sum(len(s['pieces']) for s in sections), 'pieces')
